//numeric separator

let million = 1_000_000; // 1 million
let billion = 1_000_000_000; // 1 billion
let hexadecimal = 0xFF_FF_FF; // hexadecimal representation of 16777215 

console.log(million); // 1000000
console.log(billion); // 1000000000
console.log(hexadecimal); // 16777215

//numeric separator can be used to improve the readability of large numbers.