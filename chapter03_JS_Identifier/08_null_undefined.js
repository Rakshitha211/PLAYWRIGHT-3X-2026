/*  Simple undefinied variable */
let a;
console.log(a); // undefined

/*  Simple null variable */
let b = null;
console.log(b); // null 

//undefined and null are both primitive values in JavaScript, 
// but they have different meanings and uses.


var x;
console.log(x); // undefined

let profilePicture = null;
console.log(profilePicture); // null
console.log(typeof profilePicture); // object

//undefined is a type itself (undefined), while null is an object. 
//undefined is used to indicate that a variable has not been assigned a value, 
// while null is used to indicate the intentional absence of any object value.